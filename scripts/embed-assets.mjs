// Packages web/dist into src/embedded-assets.ts so the Worker can serve the site by itself.
// Used by `npm run deploy:bundled`, which restores the empty stub afterwards. Skips the unused promo clips.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dist = join(root, 'web/dist');
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml', '.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.json': 'application/json', '.yaml': 'text/yaml; charset=utf-8', '.txt': 'text/plain; charset=utf-8', '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
};
const out = {};
let total = 0;
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { if (name !== 'clips') walk(p); continue; }
    const type = TYPES[extname(name).toLowerCase()];
    if (!type) { console.warn('skipping unknown type', name); continue; }
    const buf = readFileSync(p);
    total += buf.length;
    out['/' + relative(dist, p).split('\\').join('/')] = { type, b64: buf.toString('base64') };
  }
})(dist);
if (!out['/index.html']) throw new Error('web/dist/index.html missing: run `npm run build:web` first');
writeFileSync(join(root, 'src/embedded-assets.ts'),
  '// GENERATED by scripts/embed-assets.mjs. Do not commit; `git checkout src/embedded-assets.ts` restores the stub.\n' +
  'export const EMBEDDED: Record<string, { type: string; b64: string }> = ' + JSON.stringify(out) + ';\n');
console.log(`embedded ${Object.keys(out).length} files, ${(total / 1024).toFixed(0)} KB raw`);
